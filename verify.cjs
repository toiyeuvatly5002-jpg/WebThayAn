const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const {seed,run}=require("../service.cjs");
const db=seed("79321");
const call=(action,body,token)=>run(db,action,body,token,"build-test");
const login=code=>call("login",{code}).secret;
const admin=login("79321");
const students=["A","B"].map(name=>call("issue",{name,role:"student"},admin).code);
const [a,b]=students.map(login);
assert.deepEqual(call("catalog",{},a).items,[]);
assert.throws(()=>call("templateAdmin",{},a),e=>e.status===403);
const sample={name:"sample.sty",source:"% template",conan:true,agasa:true};
call("setTemplate",{slot:"style",value:sample},admin);
const solution=["Giải: $1+1=2$"];
const paper={title:"Toán",grade:1,subject:"Toán",track:"Theo chương trình",category:"Bài tập luyện tập",type:"quiz",questions:[{text:"1+1?",options:["1","2","3","4"],key:1}],solutions:solution};
const {id}=call("publish",paper,admin);
assert(!("art" in db.items[0]));
assert(!("solutions" in call("open",{id},a)));
assert(!("solutions" in call("catalog",{},a).items[0]));
assert(!("source" in call("open",{id},a).art));
const score=call("submit",{id,answers:["B"],attemptId:"attempt-test-123"},a);
assert.equal(score.total,10);
assert.equal(call("history",{code:students[0]},b).rows.length,0);
assert.equal(call("history",{},a).rows[0].attempt,score.attempt);
assert.throws(()=>call("review",{attempt:score.attempt},b),e=>e.status===404);
assert.throws(()=>call("review",{attempt:score.attempt},""),e=>e.status===401);
assert.deepEqual(call("review",{attempt:score.attempt},a).solutions,solution);
call("setTemplate",{slot:"style",value:{...sample,source:"% replaced"}},admin);
assert(!JSON.stringify(db).includes("% template"));
call("setTemplate",{slot:"style",value:null},admin);
assert.equal(call("open",{id},a).art.conan,false);
assert.equal(Object.values(db.results).length,1);
assert(!("solutions" in Object.values(db.results)[0]));
const pub=path.join(__dirname,"../public"),ctx=vm.createContext({});
for(const m of fs.readFileSync(path.join(pub,"index.html"),"utf8").matchAll(/<script src="([^"]+)"/g)){
 const script=fs.readFileSync(path.join(pub,m[1]),"utf8");new vm.Script(script);
 if(["tex.js","management.js"].includes(m[1]))vm.runInContext(script,ctx);
}
assert.deepEqual([...ctx.parseSolutions("Câu 1: a\nCâu 2: b",2)],["a","b"]);
assert.deepEqual([...ctx.parseSolutions(String.raw`\hdg\khung{a {b}} \hdg\khung{c}`,2)],["a {b}","c"]);
assert.throws(()=>ctx.parseSolutions("Câu 1: x",2));
console.log("OK: thư viện mới, mẫu chung, phân quyền, nộp bài, lịch sử, lời giải và tài nguyên web.");
